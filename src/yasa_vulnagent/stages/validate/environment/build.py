from __future__ import annotations

import hashlib
import os
import shutil
from pathlib import Path
from typing import Any, Mapping

from langgraph.runtime import Runtime

from ....config import Settings
from ....workflow.state import RunContext
from .docker import DockerClient
from .schema import EnvironmentState, canonical_hash
from .storage import (
    attempt_dir,
    paths_from_state,
    write_json,
    write_text,
)

_EXCLUDED_DIRS = {
    ".git",
    ".yasa-vulnagent",
    ".venv",
    "venv",
    "__pycache__",
    "node_modules",
    "target",
    "build",
    "dist",
    "coverage",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    ".tox",
    ".nox",
}
_SECRET_NAMES = {
    ".env",
    "id_rsa",
    "id_ed25519",
    "credentials.json",
    "secrets.json",
    "secrets.yaml",
    "secrets.yml",
    ".npmrc",
    ".pypirc",
    ".netrc",
}
_SECRET_SUFFIXES = (".pem", ".key", ".p12", ".pfx")


class BuildContextError(RuntimeError):
    """Raised when a safe Docker build context cannot be materialized."""


def render_dockerfile(plan: Mapping[str, Any]) -> str:
    instructions = plan.get("dockerfile")
    if not isinstance(instructions, list) or not instructions:
        raise ValueError("plan has no Dockerfile instructions")
    lines: list[str] = ["# Generated by VulAgent environment agent"]
    for item in instructions:
        if not isinstance(item, Mapping):
            raise ValueError("Dockerfile instruction must be an object")
        name = str(item.get("instruction", "") or "").strip().upper()
        arguments = str(item.get("arguments", "") or "").strip()
        if not name or not arguments:
            raise ValueError("Dockerfile instruction needs a name and arguments")
        lines.append(f"{name} {arguments}")
    return "\n".join(lines) + "\n"


def create_build_context(
    repository: Path,
    destination: Path,
    settings: Settings,
) -> dict[str, Any]:
    repository = repository.expanduser().resolve()
    destination = destination.expanduser().resolve()
    root = destination.parent.resolve()
    if destination.name != "build-context" or not _under(root, destination):
        raise BuildContextError(f"refusing to replace unexpected context path: {destination}")
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    files = 0
    total_bytes = 0
    digest = hashlib.sha256()
    excluded: list[str] = []
    for source in _iter_source_files(repository, destination, excluded):
        relative = source.relative_to(repository).as_posix()
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            shutil.copy2(source, target)
            size = target.stat().st_size
        except OSError as exc:
            raise BuildContextError(f"cannot copy {relative}: {exc}") from exc
        files += 1
        total_bytes += size
        if files > settings.validate_env_max_context_files:
            raise BuildContextError("build context file limit exceeded")
        if total_bytes > settings.validate_env_max_context_bytes:
            raise BuildContextError("build context byte limit exceeded")
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        with target.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
    dockerignore = _dockerignore(excluded)
    (destination / ".dockerignore").write_text(dockerignore, encoding="utf-8")
    digest.update(b".dockerignore\0")
    digest.update(dockerignore.encode("utf-8"))
    return {
        "context": str(destination),
        "context_hash": digest.hexdigest(),
        "file_count": files,
        "bytes": total_bytes,
        "excluded": excluded[:200],
    }


def build_node(
    state: EnvironmentState,
    runtime: Runtime[RunContext] | None = None,
) -> dict[str, Any]:
    context = runtime.context if runtime is not None else None
    if context is None:
        from ....config import load_settings

        context = RunContext(settings=load_settings())
    settings = context.settings
    docker = context.docker or DockerClient(settings)
    plan = dict(state.get("approved_plan") or state.get("plan") or {})
    attempt = int(state.get("attempt", 0)) + 1
    if attempt > settings.validate_env_max_build_attempts:
        return {
            **dict(state),
            "status": "blocked",
            "next_action": "classify",
            "stop_reason": "build_attempt_limit",
            "attempt": attempt - 1,
            "errors": [*state.get("errors", []), "build attempt limit reached"],
        }
    paths = paths_from_state(state)
    paths.root.mkdir(parents=True, exist_ok=True)
    attempt_path = attempt_dir(state, attempt)
    attempt_path.mkdir(parents=True, exist_ok=True)
    try:
        dockerfile = render_dockerfile(plan)
        write_text(paths.dockerfile, dockerfile)
        context_info = create_build_context(
            Path(str(state["repository"])),
            paths.work_dir / "build-context",
            settings,
        )
        dockerignore_text = _dockerignore(context_info["excluded"])
        write_text(paths.work_dir / "build-context" / ".dockerignore", dockerignore_text)
        write_text(paths.dockerignore, dockerignore_text)
    except (OSError, ValueError, BuildContextError) as exc:
        return {
            **dict(state),
            "status": "blocked",
            "next_action": "classify",
            "stop_reason": "build_context_error",
            "attempt": attempt,
            "errors": [*state.get("errors", []), str(exc)],
        }
    environment_hash = canonical_hash(
        {
            "plan": plan,
            "context_hash": context_info["context_hash"],
            "source_revision": state.get("source_revision", ""),
        }
    )[:16]
    tag = f"yasa-validate:{environment_hash}"
    log_path = attempt_path / "build.log"
    labels = {
        "yasa.run_id": str(state.get("run_id", "")),
        "yasa.environment_hash": environment_hash,
    }
    result = docker.build(
        context=Path(context_info["context"]),
        dockerfile=paths.dockerfile,
        tag=tag,
        labels=labels,
        timeout=settings.validate_docker_build_timeout,
        log_path=log_path,
    )
    warnings = list(state.get("warnings", []))
    build_record = {
        "status": "complete" if result.ok else "failed",
        "attempt": attempt,
        "tag": tag,
        "environment_hash": environment_hash,
        "context_hash": context_info["context_hash"],
        "context_file_count": context_info["file_count"],
        "context_bytes": context_info["bytes"],
        "excluded": context_info["excluded"],
        "exit_code": result.returncode,
        "timed_out": result.timed_out,
        "duration_seconds": round(result.duration, 3),
        "command": list(result.args),
        "log_file": str(log_path),
        "error": result.error,
        "output_tail": result.tail(4000),
    }
    write_json(attempt_path / "build.json", build_record)
    if result.ok:
        image = docker.image_inspect(tag)
        if image.get("status") != "ready":
            return {
                **dict(state),
                "status": "failed",
                "next_action": "classify",
                "stop_reason": "image_inspect_failed",
                "attempt": attempt,
                "build": build_record,
                "warnings": warnings,
                "errors": [*state.get("errors", []), str(image.get("error", "image inspect failed"))],
            }
        return {
            **dict(state),
            "status": "running",
            "next_action": "smoke",
            "attempt": attempt,
            "build": build_record,
            "image": {"tag": tag, **image},
            "environment_hash": environment_hash,
            "context_hash": context_info["context_hash"],
            "warnings": warnings,
        }
    failure = {
        "phase": "build",
        "attempt": attempt,
        "exit_code": result.returncode,
        "timed_out": result.timed_out,
        "command": list(result.args),
        "log_file": str(log_path),
        "output_tail": result.tail(6000),
        "error": result.error,
        "plan_hash": str(state.get("plan_hash", "")),
    }
    if _infrastructure_failure(result):
        return {
            **dict(state),
            "status": "blocked",
            "next_action": "classify",
            "stop_reason": "docker_build_infrastructure",
            "attempt": attempt,
            "build": build_record,
            "failure": failure,
            "errors": [*state.get("errors", []), "Docker build infrastructure failed"],
        }
    return {
        **dict(state),
        "status": "running",
        "next_action": "diagnose",
        "attempt": attempt,
        "build": build_record,
        "failure": failure,
        "failed_plan_hash": str(state.get("plan_hash", "")),
        "warnings": warnings,
    }


def _iter_source_files(repository: Path, destination: Path, excluded: list[str]):
    for root, directories, files in os.walk(repository):
        current = Path(root)
        kept: list[str] = []
        for name in sorted(directories):
            candidate = current / name
            relative = candidate.relative_to(repository).as_posix()
            if candidate.is_symlink() and not _under(repository, candidate.resolve()):
                excluded.append(relative)
                continue
            if (
                name in _EXCLUDED_DIRS
                or _secret_name(name)
                or candidate.resolve() == destination
                or _under(destination, candidate)
            ):
                excluded.append(relative)
                continue
            kept.append(name)
        directories[:] = kept
        for name in sorted(files):
            candidate = current / name
            relative = candidate.relative_to(repository).as_posix()
            if _secret_name(name):
                excluded.append(relative)
                continue
            if candidate.is_symlink() and not _under(repository, candidate.resolve()):
                excluded.append(relative)
                continue
            yield candidate


def _secret_name(name: str) -> bool:
    lowered = name.lower()
    return lowered in _SECRET_NAMES or lowered.endswith(_SECRET_SUFFIXES) or lowered.startswith(".env.")


def _dockerignore(excluded: list[str]) -> str:
    lines = [
        ".git",
        ".yasa-vulnagent",
        ".env",
        ".env.*",
        "*.pem",
        "*.key",
        "*.p12",
        "*.pfx",
        "id_rsa",
        "id_ed25519",
        "credentials.json",
        "secrets.json",
        "secrets.yaml",
        "secrets.yml",
        ".npmrc",
        ".pypirc",
        ".netrc",
    ]
    lines.extend(item for item in excluded if item and item not in lines)
    return "\n".join(lines) + "\n"


def _under(root: Path, candidate: Path) -> bool:
    try:
        candidate.resolve().relative_to(root.resolve())
        return True
    except ValueError:
        return False


def _infrastructure_failure(result: Any) -> bool:
    text = f"{getattr(result, 'error', '')}\n{getattr(result, 'stderr', '')}".lower()
    return any(
        marker in text
        for marker in (
            "docker binary not found",
            "permission denied while trying to connect to the docker api",
            "permission denied while trying to connect to the docker daemon",
            "cannot connect to the docker daemon",
            "is the docker daemon running",
        )
    )
